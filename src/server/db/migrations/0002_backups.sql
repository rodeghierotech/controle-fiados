create table backup_execucoes (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references administradores(user_id) on delete restrict,
  objeto text not null,
  criado_em timestamptz not null,
  tamanho_bytes bigint not null check (tamanho_bytes > 0),
  checksum text not null check (length(checksum) = 64),
  constraint uq_backup_execucoes_objeto unique (objeto)
);

create index idx_backup_execucoes_owner_criado on backup_execucoes(owner_id, criado_em desc);
